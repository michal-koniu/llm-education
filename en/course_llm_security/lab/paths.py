"""All filesystem locations of the lab, resolved relative to this package.

Nothing here depends on the current working directory, so the lab behaves the
same whether you run it from its parent directory or from anywhere else with
PYTHONPATH pointing at that parent.
"""
import os
from pathlib import Path

LAB_DIR = Path(__file__).resolve().parent      # .../lab
LAB_PARENT = LAB_DIR.parent                    # the directory you run commands from
RUNTIME = LAB_DIR / "runtime"                  # everything the lab writes at run time
DATA = LAB_DIR / "data"                        # generated by setup_lab
DOCS = DATA / "docs"                           # the RAG store (untrusted)
FILES = DATA / "files"                         # the user's private files
WEB = LAB_DIR / "web"                          # the fixture "internet" (untrusted)
CASES = LAB_DIR / "cases"

SECRETS = RUNTIME / "secrets.json"
OUTBOX = RUNTIME / "outbox.jsonl"
MEMORY = RUNTIME / "memory.jsonl"
ATTACKER_LOG = RUNTIME / "attacker.log"
TRACES = RUNTIME / "traces.jsonl"
SCOREBOARD = RUNTIME / "scoreboard.csv"
RUNS = RUNTIME / "runs"                        # per-harness-run trace dumps

# The only places a case is allowed to plant files into (relative to LAB_DIR).
PLANT_ROOTS = ("web", "data/docs", "data/files")

HOST = "127.0.0.1"   # never change this: the lab must not be reachable from your LAN
# Ports can be moved with environment variables if something else already uses them
# (cases are written with 8765/8766; the harness rewrites those URLs to the ports set here).
WEB_PORT = int(os.environ.get("LAB_WEB_PORT", "8765"))
ATTACKER_PORT = int(os.environ.get("LAB_ATTACKER_PORT", "8766"))
UI_PORT = int(os.environ.get("LAB_UI_PORT", "8760"))
